package com.opentune.data.metadata

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class SongCreditsTest {
    private val studioSheet = """
        Provided to YouTube by Universal Music Group

        Blinding Lights · The Weeknd

        After Hours

        ℗ 2020 The Weeknd XO, Inc., Manufactured and Marketed by Republic Records

        Released on: 2020-03-20

        Producer: Max Martin
        Producer, Programmer: Oscar Holter
        Associated  Performer, Background  Vocalist, Bass, Drums, Guitar: Max Martin
        Studio  Personnel, Mixer: Serban Ghenea
        Mastering  Engineer, Studio  Personnel: Dave Kutch
        Composer  Lyricist: Abel Tesfaye
        Composer  Lyricist: Max Martin
        Music  Publisher: Kobalt Music Publishing

        Auto-generated by YouTube.
    """.trimIndent()

    private val filmSong = """
        Provided to YouTube by T-Series

        Tum Hi Ho · Mithoon · Arijit Singh

        Aashiqui 2: Original Motion Picture Soundtrack

        ℗ 2013 Super Cassettes Industries Private Limited

        Released on: 2013-04-01

        Composer: Mithoon
        Lyricist: Mithoon

        Auto-generated by YouTube.
    """.trimIndent()

    @Test fun studioSheetSplitsIntoThreeGroups() {
        val c = SongCreditsRepository.parse(studioSheet)!!
        assertEquals("Universal Music Group", c.label)
        assertEquals("2020-03-20", c.released)
        assertEquals(listOf("The Weeknd", "Max Martin"), c.performers.map { it.name })
        assertEquals(Credit("The Weeknd", listOf("Artist")), c.performers[0])
        // The generic "Associated Performer" goes when there is something more telling.
        assertEquals(listOf("Background Vocalist", "Bass", "Drums", "Guitar"), c.performers[1].roles)
        assertEquals(listOf("Abel Tesfaye", "Max Martin"), c.composition.map { it.name })
        assertEquals(listOf("Composer & Lyricist"), c.composition[0].roles)
        assertEquals(
            listOf(Credit("Max Martin", listOf("Producer")), Credit("Oscar Holter", listOf("Producer", "Programmer")),
                Credit("Serban Ghenea", listOf("Mixer")), Credit("Dave Kutch", listOf("Mastering Engineer"))),
            c.production,
        )
    }

    @Test fun filmSongKeepsItsMainArtistsAndAlbumColonIsNotACredit() {
        val c = SongCreditsRepository.parse(filmSong)!!
        assertEquals(listOf("Mithoon", "Arijit Singh"), c.performers.map { it.name })
        assertEquals(listOf(Credit("Mithoon", listOf("Composer", "Lyricist"))), c.composition)
        assertTrue(c.production.isEmpty())
    }

    @Test fun uploadersOwnNotesAreNotCredits() {
        assertNull(SongCreditsRepository.parse("Official video\nDirector: Someone\nFollow me: @someone"))
    }
}
