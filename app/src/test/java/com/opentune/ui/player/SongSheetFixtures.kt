    /** Covers and portraits for the fake image loader: soft gradients standing in for pictures. */
    fun installImages(context: Context) {
        fun picture(a: Int, b: Int, face: Boolean): coil3.Image {
            val size = 480
            val bmp = Bitmap.createBitmap(size, size, Bitmap.Config.ARGB_8888)
            val canvas = Canvas(bmp)
            canvas.drawRect(0f, 0f, size.toFloat(), size.toFloat(), Paint().apply {
                shader = LinearGradient(0f, 0f, size.toFloat(), size.toFloat(), a, b, Shader.TileMode.CLAMP)
            })
            val glow = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                shader = RadialGradient(size * 0.5f, if (face) size * 0.42f else size * 0.35f, size * 0.32f,
                    0xCCFFFFFF.toInt(), 0x00FFFFFF, Shader.TileMode.CLAMP)
            }
            canvas.drawCircle(size * 0.5f, if (face) size * 0.42f else size * 0.35f, size * 0.32f, glow)
            if (face) canvas.drawCircle(size * 0.5f, size * 1.02f, size * 0.42f, Paint(Paint.ANTI_ALIAS_FLAG).apply { color = 0x66000000 })
            return BitmapDrawable(context.resources, bmp).asImage()
        }
        val engine = FakeImageLoaderEngine.Builder()
            .intercept({ it is String && it.contains("img.test/cover") }, picture(0xFFE46A4B.toInt(), 0xFF3B1E5A.toInt(), face = false))
            .intercept({ it is String && it.contains("img.test/nova") }, picture(0xFF7FB7D9.toInt(), 0xFF2D4F7A.toInt(), face = true))
            .intercept({ it is String && it.contains("img.test/tomas") }, picture(0xFFD9B77F.toInt(), 0xFF7A4B2D.toInt(), face = true))
            .build()
        SingletonImageLoader.setUnsafe(ImageLoader.Builder(context).components { add(engine) }.build())
    }
