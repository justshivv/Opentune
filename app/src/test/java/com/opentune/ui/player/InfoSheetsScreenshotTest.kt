    private fun credits(cover: Cover) {
        val s = song(cover)
        SongCreditsRepository.remember(buildJsonObject {
            putJsonObject("videoDetails") {
                put("videoId", s.videoId)
                put("shortDescription", description)
            }
        })
        inPlayer(cover) { CreditsSheet(s, onDismiss = {}) }
        settle()
    }

    @Test fun creditsDeep() { credits(Cover.DEEP); shoot("credits-deep") }
    @Test fun creditsPale() { credits(Cover.PALE); shoot("credits-pale") }

