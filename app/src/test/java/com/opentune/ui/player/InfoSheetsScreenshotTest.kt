/**
 * The player's "…" menu (the Lite page and the rising card), the song sheet, About song,
 * the credits page and the "Also available on" row, over the player, for two covers: a deep,
 * coloured one and a pale one. Drawn to build/screenshots/info-sheets. Every song, artist,
 * credit and text in them is invented.
 */
@RunWith(RobolectricTestRunner::class)
@GraphicsMode(GraphicsMode.Mode.NATIVE)
@Config(sdk = [35], qualifiers = "w411dp-h891dp-xxhdpi", application = Application::class)
class InfoSheetsScreenshotTest {
    @get:Rule val compose = createAndroidComposeRule<ComponentActivity>()

    private enum class Cover(val url: String, val tag: String) {
        DEEP("https://img.test/cover-deep", "deep"),
        PALE("https://img.test/cover-pale", "pale"),
    }

    private fun song(cover: Cover) = Song(
        if (cover == Cover.DEEP) "dRftW00dS01" else "pAleSh0reS2",
        if (cover == Cover.DEEP) "Driftwood Signals" else "Pale Shore",
        "Ivo Marlowe, Sela Quinn", cover.url,
        durationText = "3:58", albumId = "MPREb_tidewater", albumName = "Tidewater Rooms",
    )

    private val description = """
        Provided to YouTube by Saltmarsh Sound

        Driftwood Signals · Ivo Marlowe · Sela Quinn

        Tidewater Rooms

        ℗ 2026 Saltmarsh Sound

        Released on: 2026-03-14

        Composer, Lyricist: Ivo Marlowe
        Composer: Sela Quinn
        Lyricist: Rhea Tamsin
        Background Vocalist: Odile Faro
        Guitar: Kasper Lund
        Producer: Bram Okonkwo
        Recording Engineer: Teo Halloran
        Mixing Engineer: Wren Abara
        Mastering Engineer: Juno Petrakis

        Auto-generated by YouTube.
    """.trimIndent()

    private fun info(loadingLinks: Boolean = false): SongInfo {
        val text = tidyDescription(description)!!
        return SongInfo(
            description = text,
            credits = SongCreditsRepository.parse(text),
            genre = "Alternative",
            released = "2026-03-14",
            trackNumber = 4,
            appleUrl = "https://music.apple.com/us/song/driftwood-signals/1",
            photos = mapOf("Ivo Marlowe" to "https://img.test/ivo", "Sela Quinn" to "https://img.test/sela"),
            about = listOf(
                AboutText(
                    AboutSource.WIKIPEDIA,
                    "\"Driftwood Signals\" is a song by Ivo Marlowe and Sela Quinn, the fourth track of their shared record " +
                        "Tidewater Rooms. Built on a looped pump organ and brushed drums, it follows two lighthouse keepers who " +
                        "trade messages across a bay with lamps. It was recorded in a boathouse over three days in early spring.",
                    "https://en.wikipedia.org/wiki/Driftwood_Signals",
                ),
            ),
            links = if (loadingLinks) emptyList() else listOf(
                ServiceLink(MusicService.SPOTIFY, "https://open.spotify.com/track/1"),
                ServiceLink(MusicService.DEEZER, "https://www.deezer.com/track/1"),
            ),
            pending = if (loadingLinks) setOf(SongInfoPart.LINKS) else emptySet(),
        )
    }

    @Before fun setUp() {
        val context = ApplicationProvider.getApplicationContext<Application>()
        AppSettings.init(context)
        LibraryStore.init(context)
        AppSettings.updateUi { it.copy(pageLayout = PageLayout.POSTER, reduceBlur = false, liteThreeDotMenu = false) }
        installCovers(context)
    }

    @After fun reset() {
        AppSettings.updateUi { it.copy(pageLayout = PageLayout.CLASSIC, liteThreeDotMenu = false) }
        AppSettings.updateTheme { it.copy(playerBackground = PlayerBackground.BLUR) }
        Cover.entries.forEach { LibraryStore.setLiked(song(it), false) }
    }

    /** Inside the player: its theme (the Apple-inspired style's, whose sheets were grey), over a stand-in for it. */
    private fun inPlayer(cover: Cover, background: PlayerBackground = PlayerBackground.BLUR, content: @Composable () -> Unit) {
        compose.setContent {
            OpenTuneTheme(ThemeSettings(mode = ThemeMode.DARK, dynamicColor = false)) {
                val theme = ThemeSettings(mode = ThemeMode.DARK, playerBackground = background)
                CompositionLocalProvider(LocalSongSheet provides {}) {
                    PlayerTheme(seed = com.opentune.ui.theme.rememberArtworkSeed(cover.url), settings = theme, neutral = true) {
                        PlayerStandIn(song(cover), black = background == PlayerBackground.AMOLED)
                        content()
                    }
                }
            }
        }
        settle()
    }

    private fun settle() {
        repeat(4) {
            compose.mainClock.advanceTimeBy(500)
            compose.waitForIdle()
        }
    }

    private fun shoot(name: String) {
        compose.waitForIdle()
        val back = compose.activity.window.decorView
        val bitmap = Bitmap.createBitmap(back.width, back.height, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(bitmap)
        back.draw(canvas)
        val sheet = ShadowDialog.getLatestDialog().window!!.decorView
        canvas.translate(0f, (back.height - sheet.height).toFloat())
        sheet.draw(canvas)
        File("build/screenshots/info-sheets/$name.png").apply { parentFile!!.mkdirs() }
            .outputStream().use { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }
    }

    private val menuActions = SongMenuActions({}, {}, {}, {}, {})

    private fun menu(cover: Cover, lite: Boolean, liked: Boolean, poster: Boolean = true) {
        AppSettings.updateUi { it.copy(liteThreeDotMenu = lite, pageLayout = if (poster) PageLayout.POSTER else PageLayout.CLASSIC) }
        LibraryStore.setLiked(song(cover), liked)
        inPlayer(cover) {
            CompositionLocalProvider(LocalSongMenu provides menuActions) {
                SongMenuSheet(song(cover), onDismiss = {}, startExpanded = true)
            }
        }
        compose.onNodeWithText("Play next").assertExists()
    }

    private fun songSheet(cover: Cover, about: Boolean = false, info: SongInfo = info()) {
        inPlayer(cover) {
            SongInfoSheets(
                song(cover), info,
                SongSheetActions(openArtist = {}, openAlbum = {}, streamInfo = {}, allCredits = {}),
                onDismiss = {}, durationMs = 238_000, startOnAbout = about,
            )
        }
    }

    private fun scrollAboutToEnd() {
        repeat(4) {
            compose.onNode(hasScrollAction() and hasAnyDescendant(hasText("Genre")))
                .performTouchInput { swipeUp(startY = bottom - 40f, endY = top + 40f, durationMillis = 400) }
            compose.mainClock.advanceTimeBy(1_500)
        }
        compose.waitForIdle()
    }

