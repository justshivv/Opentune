            OpenTuneTheme(ThemeSettings(mode = ThemeMode.LIGHT, dynamicColor = false)) {
                PlayerStandIn(s, black = false)
                CreditsSheet(s, onDismiss = {})
            }
        }
        settle()
        shoot("credits-light-theme")
    }

    /** Covers and portraits for the fake image loader. */
    private fun installCovers(context: Context) {
        fun picture(a: Int, b: Int, glow: Int, face: Boolean): coil3.Image {
            val size = 480
            val bmp = Bitmap.createBitmap(size, size, Bitmap.Config.ARGB_8888)
            val canvas = Canvas(bmp)
            canvas.drawRect(0f, 0f, size.toFloat(), size.toFloat(), Paint().apply {
                shader = LinearGradient(0f, 0f, size.toFloat(), size.toFloat(), a, b, Shader.TileMode.CLAMP)
            })
            val cy = if (face) size * 0.42f else size * 0.62f
            canvas.drawCircle(size * 0.5f, cy, size * 0.3f, Paint(Paint.ANTI_ALIAS_FLAG).apply {
                shader = RadialGradient(size * 0.5f, cy, size * 0.3f, glow, glow and 0x00FFFFFF, Shader.TileMode.CLAMP)
            })
            if (face) canvas.drawCircle(size * 0.5f, size * 1.02f, size * 0.42f, Paint(Paint.ANTI_ALIAS_FLAG).apply { color = 0x66000000 })
            return BitmapDrawable(context.resources, bmp).asImage()
        }
        val engine = FakeImageLoaderEngine.Builder()
            .intercept({ it is String && it.contains("cover-deep") }, picture(0xFF0E5A63.toInt(), 0xFF101C3A.toInt(), 0xCCE0A04A.toInt(), face = false))
            .intercept({ it is String && it.contains("cover-pale") }, picture(0xFFF3EBDD.toInt(), 0xFFE6D3BF.toInt(), 0xCCFFFFFF.toInt(), face = false))
            .intercept({ it is String && it.contains("img.test/ivo") }, picture(0xFF9FB8C9.toInt(), 0xFF3B4F63.toInt(), 0xCCFFFFFF.toInt(), face = true))
            .intercept({ it is String && it.contains("img.test/sela") }, picture(0xFFD8A98C.toInt(), 0xFF6A3D2C.toInt(), 0xCCFFFFFF.toInt(), face = true))
            .build()
        SingletonImageLoader.setUnsafe(ImageLoader.Builder(context).components { add(engine) }.build())
    }
}

/** Something like the full player behind: its cover-coloured backdrop, the cover, the title. */
@Composable
private fun PlayerStandIn(song: Song, black: Boolean) {
    val tones = rememberCoverTones(song.thumbnailUrl).target
    val dark = MaterialTheme.colorScheme.surface.luminance() < 0.5f
    val brush = if (black) Brush.verticalGradient(listOf(androidx.compose.ui.graphics.Color.Black, androidx.compose.ui.graphics.Color.Black))
    else if (dark) Brush.verticalGradient(listOf(tones.deep, tones.base))
    else Brush.verticalGradient(listOf(MaterialTheme.colorScheme.primaryContainer, MaterialTheme.colorScheme.surface))
    Box(Modifier.fillMaxSize().background(brush)) {
        Column(Modifier.statusBarsPadding().padding(horizontal = 28.dp, vertical = 64.dp)) {
            Artwork(song.thumbnailUrl, Modifier.fillMaxWidth().aspectRatio(1f), RoundedCornerShape(28.dp))
            Text(song.title, style = MaterialTheme.typography.headlineSmall, fontWeight = FontWeight.Bold, modifier = Modifier.padding(top = 28.dp))
            Text(song.artist, style = MaterialTheme.typography.titleMedium, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
    }
}

